const fs=require('fs'),vm=require('vm'),assert=require('assert');
const source=fs.readFileSync(__dirname+'/static/redesign.js','utf8');
const start=source.indexOf("const portraitPrompt=");
const end=source.indexOf("function renderPortraitEditor()",start);
const context={url:x=>x?.full||''};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+';this.updatePortraitPrompt=updatePortraitPrompt;',context);
const old='根据所选人物参考创作自然真实的人物写真，保留参考图中指定的衣服、姿势和人物特征，画面完整，光线自然。';
const item={outfit:{id:'A',full:'/a'},promptOverride:old+'\n用户自己添加的要求',promptKey:'old'};
let first=context.updatePortraitPrompt(item);
assert(first.includes('用户自己添加的要求')&&first.includes('【人物比例与衣装细节】')&&first.includes('装饰配件'));
item.promptOverride=first.replace('用户自己添加的要求','用户修改的要求');
item.outfit={id:'B',full:'/b'};
let second=context.updatePortraitPrompt(item);
assert(second.includes('用户修改的要求')&&second.includes('衣装参考，请保持服装款式、颜色、材质和配饰。'));
assert(!second.includes('衣服（A）')&&!second.includes('衣服（B）'));
const roles={outfit:{full:'/o'},pose:{full:'/p'},face:{full:'/f'}};
let rolePrompt=context.updatePortraitPrompt(roles);
assert(rolePrompt.includes('第 1 张：衣装参考，请保持服装款式、颜色、材质和配饰。'));
assert(rolePrompt.includes('第 2 张：姿势参考图，请参考身体姿态、手脚位置和朝向。'));
assert(rolePrompt.includes('第 3 张：脸部参考，请保持人物的面部特征和身份一致。'));
assert.strictEqual((second.match(/【人物比例与衣装细节】/g)||[]).length,1);
item.promptOverride=second.replace('【人物比例与衣装细节】','【我自定义的细节】');
assert(!context.updatePortraitPrompt(item).includes('【人物比例与衣装细节】'));
console.log('Portrait quality instructions, migration, custom edits and reference updates passed.');
context.styles=[{id:'FA-036',name:'画风测试'}];
const styled={outfit:{full:'/o'},pose:{full:'/p'},face:{full:'/f'},style:'FA-036'};
let styledText=context.updatePortraitPrompt(styled);
assert(styledText.includes('【写真画风】')&&!styledText.includes('自然真实的人物写真'));
styled.promptOverride=styledText+'\n自定义背景保留';
styled.style='';
let realistic=context.updatePortraitPrompt(styled);
assert(!realistic.includes('【写真画风】')&&realistic.includes('自然真实的人物写真')&&realistic.includes('自定义背景保留'));
console.log('Portrait style transitions preserve custom edits and restore realistic mode.');
